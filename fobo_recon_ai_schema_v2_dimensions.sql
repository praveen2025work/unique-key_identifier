--------------------------------------------------------------------------------
-- FOBO Reconciliation GenAI Platform - region and business-date dimension layer
-- Oracle 19c. Apply after fobo_recon_ai_schema.sql.
--
-- REPLACES from v1:  RECON_SESSION, RECON_EXCEPTION, ANALYSIS_CASE
--                    (grain and partitioning both change - drop and recreate)
-- SUPERSEDES from v1: RECON_REGION (now REGION + RECON_REGION_SCOPE)
-- UNCHANGED from v1:  all CONFIG tables except RECON_REGION, all ANALYSIS
--                     child tables, all AUDIT tables
--
-- The grain question
--   RECON_SESSION is the fact table at grain (RECON, REGION, BUSINESS_DATE).
--   REGION_DAY and RECON_DAY are the two rollups over it:
--
--     REGION_DAY  = one controller's shift.   "APAC, 08 Sep, all recons"
--     RECON_DAY   = one recon owner's close.  "Cash vs nostro, 08 Sep, all regions"
--
--   Both need independent status and independent sign-off. A controller signs
--   off their region across recons. A recon owner signs off their recon across
--   regions, and cannot do so until every regional session beneath it closes.
--------------------------------------------------------------------------------


--------------------------------------------------------------------------------
-- 1. THE TWO DIMENSIONS
--------------------------------------------------------------------------------

-- Region is a real dimension, not a check constraint. Shift windows drive the
-- SLA trigger policy: a wave must complete before SHIFT_START_LOCAL.
CREATE TABLE REGION (
  REGION_CODE           VARCHAR2(10)    PRIMARY KEY,
  REGION_NAME           VARCHAR2(60)    NOT NULL,
  IANA_TIMEZONE         VARCHAR2(60)    NOT NULL,
  SHIFT_START_LOCAL     VARCHAR2(5)     NOT NULL,   -- 'HH24:MI'
  SHIFT_END_LOCAL       VARCHAR2(5)     NOT NULL,
  SIGN_OFF_CUTOFF_LOCAL VARCHAR2(5)     NOT NULL,
  PREPARE_LEAD_MINUTES  NUMBER(5)       DEFAULT 150 NOT NULL,
  DISPLAY_SEQ           NUMBER(3)       NOT NULL,
  IS_ACTIVE             CHAR(1)         DEFAULT 'Y' NOT NULL
);

