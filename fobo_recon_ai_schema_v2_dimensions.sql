--------------------------------------------------------------------------------
-- 4. HOT TABLES: COMPOSITE PARTITIONING ON THE TWO DIMENSIONS
--
-- REGION_CODE is denormalised onto both tables purely so Oracle can prune to a
-- subpartition. An APAC controller's queue query then reads one subpartition of
-- one monthly partition instead of scanning the interval. At 14 controllers
-- hitting these concurrently at shift start, this is the difference between a
-- sub-second board and a stalled dashboard.
--------------------------------------------------------------------------------

DROP TABLE RECON_EXCEPTION CASCADE CONSTRAINTS;

CREATE TABLE RECON_EXCEPTION (
  EXCEPTION_ID          NUMBER(19)      GENERATED ALWAYS AS IDENTITY,
  BUSINESS_DATE         DATE            NOT NULL,
  REGION_CODE           VARCHAR2(10)    NOT NULL,
  SESSION_ID            NUMBER(19)      NOT NULL,
  BOOK_ID               NUMBER(19)      NOT NULL,
  MBR_EXCEPTION_REF     VARCHAR2(80)    NOT NULL,
  BREAK_TYPE            VARCHAR2(40)    NOT NULL,
  BREAK_SIGNATURE       VARCHAR2(64)    NOT NULL,
  -- Identity of a break ACROSS dates. Hash of book + break type + source refs,
  -- deliberately excluding amount so a moving delta stays the same break.
  PERSISTENT_BREAK_KEY  VARCHAR2(64)    NOT NULL,
  FIRST_SEEN_BUS_DATE   DATE            NOT NULL,
  AGE_BUSINESS_DAYS     NUMBER(5)       DEFAULT 0 NOT NULL,
  CARRIED_FROM_EXC_ID   NUMBER(19),
  CCY                   CHAR(3)         NOT NULL,
  FO_AMOUNT             NUMBER(28,8),
  BO_AMOUNT             NUMBER(28,8),
  DELTA_AMOUNT          NUMBER(28,8)    NOT NULL,
  DELTA_BASE_AMOUNT     NUMBER(28,8),
  PRIOR_DAY_DELTA       NUMBER(28,8),
  VALUE_DATE            DATE,
  PRODUCT_CLASS         VARCHAR2(40),
  FO_SOURCE_SYSTEM      VARCHAR2(50),
  BO_SOURCE_SYSTEM      VARCHAR2(50),
  IS_MATERIAL           CHAR(1)         DEFAULT 'N' NOT NULL,
  INGESTED_TS           TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_RECON_EXCEPTION PRIMARY KEY (EXCEPTION_ID, BUSINESS_DATE),
  CONSTRAINT UK_RECON_EXCEPTION UNIQUE (MBR_EXCEPTION_REF, BUSINESS_DATE)
)
PARTITION BY RANGE (BUSINESS_DATE)
INTERVAL (NUMTOYMINTERVAL(1,'MONTH'))
SUBPARTITION BY LIST (REGION_CODE)
SUBPARTITION TEMPLATE (
  SUBPARTITION SP_APAC  VALUES ('APAC'),
  SUBPARTITION SP_EMEA  VALUES ('EMEA'),
  SUBPARTITION SP_AMER  VALUES ('AMER'),
  SUBPARTITION SP_OTHER VALUES (DEFAULT)
)
( PARTITION P_INIT VALUES LESS THAN (DATE '2026-01-01') );

CREATE INDEX IX_EXCEPTION_SIGNATURE ON RECON_EXCEPTION (BUSINESS_DATE, REGION_CODE, BREAK_SIGNATURE) LOCAL;
CREATE INDEX IX_EXCEPTION_SESSION   ON RECON_EXCEPTION (SESSION_ID, BOOK_ID) LOCAL;
-- Global index: aged-break lookup deliberately crosses business dates.
CREATE INDEX IX_EXCEPTION_PERSISTENT ON RECON_EXCEPTION (PERSISTENT_BREAK_KEY, BUSINESS_DATE DESC) GLOBAL;


