-- 2. THE TWO ROLLUPS
--------------------------------------------------------------------------------

-- One controller shift. Created by the scheduler at PREPARE_START_UTC.
CREATE TABLE REGION_DAY (
  REGION_DAY_ID         NUMBER(19)      GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  REGION_CODE           VARCHAR2(10)    NOT NULL,
  BUSINESS_DATE         DATE            NOT NULL,
  DAY_STATUS            VARCHAR2(20)    DEFAULT 'SCHEDULED' NOT NULL,
  PREPARE_START_UTC     TIMESTAMP WITH TIME ZONE,
  SHIFT_START_UTC       TIMESTAMP WITH TIME ZONE,
  SIGN_OFF_CUTOFF_UTC   TIMESTAMP WITH TIME ZONE,
  RECONS_IN_SCOPE       NUMBER(5)       DEFAULT 0 NOT NULL,
  RECONS_READY          NUMBER(5)       DEFAULT 0 NOT NULL,
  RECONS_SIGNED_OFF     NUMBER(5)       DEFAULT 0 NOT NULL,
  BOOKS_TOTAL           NUMBER(9)       DEFAULT 0 NOT NULL,
  BOOKS_AUTO_POST       NUMBER(9)       DEFAULT 0 NOT NULL,
  BOOKS_OPEN            NUMBER(9)       DEFAULT 0 NOT NULL,
  BOOKS_ANALYSED        NUMBER(9)       DEFAULT 0 NOT NULL,
  CASES_READY           NUMBER(9)       DEFAULT 0 NOT NULL,
  CASES_PENDING_REVIEW  NUMBER(9)       DEFAULT 0 NOT NULL,
  CASES_ACCEPTED        NUMBER(9)       DEFAULT 0 NOT NULL,
  CASES_REJECTED        NUMBER(9)       DEFAULT 0 NOT NULL,
  CASES_CARRIED_FORWARD NUMBER(9)       DEFAULT 0 NOT NULL,
  READY_BEFORE_SHIFT    CHAR(1),
  SIGNED_OFF_TS         TIMESTAMP WITH TIME ZONE,
  SIGNED_OFF_BY         VARCHAR2(50),
  COUNTERS_REFRESHED_TS TIMESTAMP WITH TIME ZONE,
  CONSTRAINT FK_REGION_DAY_REGION FOREIGN KEY (REGION_CODE) REFERENCES REGION (REGION_CODE),
  CONSTRAINT UK_REGION_DAY UNIQUE (REGION_CODE, BUSINESS_DATE),
  CONSTRAINT CK_REGION_DAY_STATUS CHECK (DAY_STATUS IN
    ('SCHEDULED','PREPARING','PARTIAL','READY','IN_REVIEW','SIGNED_OFF','BREACHED','HOLIDAY'))
);

CREATE INDEX IX_REGION_DAY_BOARD ON REGION_DAY (BUSINESS_DATE, REGION_CODE, DAY_STATUS);

-- One recon's global close. Unlocks only when every regional session closes.
CREATE TABLE RECON_DAY (
  RECON_DAY_ID          NUMBER(19)      GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  RECON_ID              NUMBER(19)      NOT NULL,
  BUSINESS_DATE         DATE            NOT NULL,
  DAY_STATUS            VARCHAR2(20)    DEFAULT 'SCHEDULED' NOT NULL,
  REGIONS_IN_SCOPE      NUMBER(3)       DEFAULT 0 NOT NULL,
  REGIONS_SIGNED_OFF    NUMBER(3)       DEFAULT 0 NOT NULL,
  BOOKS_TOTAL           NUMBER(9)       DEFAULT 0 NOT NULL,
  CASES_ACCEPTED        NUMBER(9)       DEFAULT 0 NOT NULL,
  CASES_CARRIED_FORWARD NUMBER(9)       DEFAULT 0 NOT NULL,
  GLOBAL_SIGN_OFF_TS    TIMESTAMP WITH TIME ZONE,
  GLOBAL_SIGN_OFF_BY    VARCHAR2(50),
  CONSTRAINT FK_RECON_DAY_RECON FOREIGN KEY (RECON_ID) REFERENCES RECON_DEFINITION (RECON_ID),
  CONSTRAINT UK_RECON_DAY UNIQUE (RECON_ID, BUSINESS_DATE),
  CONSTRAINT CK_RECON_DAY_STATUS CHECK (DAY_STATUS IN
    ('SCHEDULED','IN_PROGRESS','AWAITING_REGIONS','SIGNED_OFF','BREACHED'))
);


