-- 5. READ MODEL FOR THE REGION x DATE BOARD
--------------------------------------------------------------------------------

-- Top of the dashboard: one row per region for the selected business date.
CREATE OR REPLACE VIEW V_REGION_DAY_BOARD AS
SELECT
  rd.REGION_DAY_ID,
  rd.REGION_CODE,
  r.REGION_NAME,
  r.IANA_TIMEZONE,
  r.SHIFT_START_LOCAL,
  r.SIGN_OFF_CUTOFF_LOCAL,
  rd.BUSINESS_DATE,
  bc.IS_BUSINESS_DAY,
  bc.IS_MONTH_END,
  bc.IS_QUARTER_END,
  bc.PRIOR_BUSINESS_DATE,
  bc.NEXT_BUSINESS_DATE,
  bc.HOLIDAY_NAME,
  rd.DAY_STATUS,
  rd.RECONS_IN_SCOPE,
  rd.RECONS_READY,
  rd.RECONS_SIGNED_OFF,
  rd.BOOKS_TOTAL,
  rd.BOOKS_AUTO_POST,
  rd.BOOKS_TOTAL - rd.BOOKS_AUTO_POST        AS BOOKS_MANUAL,
  rd.BOOKS_OPEN,
  rd.BOOKS_ANALYSED,
  rd.BOOKS_OPEN - rd.BOOKS_ANALYSED          AS BOOKS_AWAITING_ANALYSIS,
  rd.CASES_PENDING_REVIEW,
  rd.CASES_ACCEPTED,
  rd.CASES_REJECTED,
  rd.CASES_CARRIED_FORWARD,
  rd.READY_BEFORE_SHIFT,
  rd.SHIFT_START_UTC,
  rd.SIGN_OFF_CUTOFF_UTC,
  rd.SIGNED_OFF_TS,
  rd.SIGNED_OFF_BY,
  CASE WHEN rd.BOOKS_OPEN = 0 THEN 0
       ELSE ROUND(rd.BOOKS_ANALYSED / rd.BOOKS_OPEN * 100, 1) END AS PCT_ANALYSED
FROM REGION_DAY rd
JOIN REGION r           ON r.REGION_CODE = rd.REGION_CODE
LEFT JOIN BUSINESS_CALENDAR bc
       ON bc.REGION_CODE = rd.REGION_CODE
      AND bc.BUSINESS_DATE = rd.BUSINESS_DATE;


-- Drill one level: recons within the selected region and date.
CREATE OR REPLACE VIEW V_REGION_DAY_RECONS AS
SELECT
  s.SESSION_ID,
  s.REGION_DAY_ID,
  s.RECON_DAY_ID,
  s.REGION_CODE,
  s.BUSINESS_DATE,
  d.RECON_CODE,
  d.RECON_NAME,
  d.RECON_TYPE,
  s.SESSION_STATUS,
  s.BOOKS_TOTAL,
  s.BOOKS_AUTO_POST,
  s.BOOKS_OPEN,
  s.BOOKS_ANALYSED,
  s.BOOKS_OPEN - s.BOOKS_ANALYSED            AS BOOKS_AWAITING_ANALYSIS,
  s.CASES_READY - s.CASES_ACCEPTED - s.CASES_REJECTED AS CASES_PENDING_REVIEW,
  s.CASES_ACCEPTED,
  s.CASES_REJECTED,
  s.CASES_CARRIED_FORWARD,
  s.FIRST_WAVE_TS,
  s.READY_TS,
  s.SIGNED_OFF_TS,
  s.SIGNED_OFF_BY,
  rdy.REGIONS_IN_SCOPE,
  rdy.REGIONS_SIGNED_OFF,
  rdy.DAY_STATUS                             AS GLOBAL_RECON_STATUS
FROM RECON_SESSION s
JOIN RECON_DEFINITION d ON d.RECON_ID = s.RECON_ID
JOIN RECON_DAY rdy      ON rdy.RECON_DAY_ID = s.RECON_DAY_ID;


-- The recon owner's cross-region view for one business date.
CREATE OR REPLACE VIEW V_RECON_DAY_GLOBAL AS
SELECT
  rdy.RECON_DAY_ID,
  rdy.RECON_ID,
  d.RECON_CODE,
  d.RECON_NAME,
  rdy.BUSINESS_DATE,
  rdy.DAY_STATUS,
  rdy.REGIONS_IN_SCOPE,
  rdy.REGIONS_SIGNED_OFF,
  LISTAGG(s.REGION_CODE || ':' || s.SESSION_STATUS, ' ')
    WITHIN GROUP (ORDER BY s.REGION_CODE)    AS REGION_STATUS_TRAIL,
  SUM(s.BOOKS_OPEN)                          AS BOOKS_OPEN,
  SUM(s.BOOKS_ANALYSED)                      AS BOOKS_ANALYSED,
  SUM(s.CASES_ACCEPTED)                      AS CASES_ACCEPTED,
  SUM(s.CASES_CARRIED_FORWARD)               AS CASES_CARRIED_FORWARD,
  rdy.GLOBAL_SIGN_OFF_TS,
  rdy.GLOBAL_SIGN_OFF_BY
FROM RECON_DAY rdy
JOIN RECON_DEFINITION d ON d.RECON_ID = rdy.RECON_ID
LEFT JOIN RECON_SESSION s ON s.RECON_DAY_ID = rdy.RECON_DAY_ID
GROUP BY rdy.RECON_DAY_ID, rdy.RECON_ID, d.RECON_CODE, d.RECON_NAME,
         rdy.BUSINESS_DATE, rdy.DAY_STATUS, rdy.REGIONS_IN_SCOPE,
         rdy.REGIONS_SIGNED_OFF, rdy.GLOBAL_SIGN_OFF_TS, rdy.GLOBAL_SIGN_OFF_BY;


-- Breaks that survived prior business dates. Controllers triage these first.
CREATE OR REPLACE VIEW V_AGED_BREAKS AS
SELECT
  e.EXCEPTION_ID,
  e.BUSINESS_DATE,
  e.REGION_CODE,
  e.SESSION_ID,
  mb.BOOK_CODE,
  mb.BOOK_NAME,
  e.PERSISTENT_BREAK_KEY,
  e.BREAK_TYPE,
  e.BREAK_SIGNATURE,
  e.CCY,
  e.DELTA_AMOUNT,
  e.PRIOR_DAY_DELTA,
  e.DELTA_AMOUNT - NVL(e.PRIOR_DAY_DELTA, 0) AS DELTA_MOVEMENT,
  e.FIRST_SEEN_BUS_DATE,
  e.AGE_BUSINESS_DAYS,
  c.CASE_ID,
  c.CASE_STATUS,
  c.CONFIDENCE_TIER,
  c.PRIOR_CASE_ID
FROM RECON_EXCEPTION e
JOIN MASTER_BOOK mb ON mb.BOOK_ID = e.BOOK_ID
LEFT JOIN ANALYSIS_CASE c
       ON c.EXCEPTION_ID = e.EXCEPTION_ID
      AND c.BUSINESS_DATE = e.BUSINESS_DATE
      AND c.CASE_STATUS <> 'SUPERSEDED'
WHERE e.AGE_BUSINESS_DAYS > 0;


--------------------------------------------------------------------------------
-- 6. COUNTER REFRESH
-- The WebSocket gateway pushes deltas; this keeps the durable rollups honest.
-- Call after each wave completes and on every terminal case decision.
--------------------------------------------------------------------------------

CREATE OR REPLACE PROCEDURE REFRESH_REGION_DAY_COUNTERS (
  p_region_day_id IN NUMBER
) AS
BEGIN
  MERGE INTO REGION_DAY t
  USING (
    SELECT
      s.REGION_DAY_ID,
      COUNT(*)                                      AS RECONS_IN_SCOPE,
      SUM(CASE WHEN s.SESSION_STATUS IN ('READY','IN_REVIEW','SIGNED_OFF')
               THEN 1 ELSE 0 END)                   AS RECONS_READY,
      SUM(CASE WHEN s.SESSION_STATUS = 'SIGNED_OFF' THEN 1 ELSE 0 END) AS RECONS_SIGNED_OFF,
      SUM(s.BOOKS_TOTAL)                            AS BOOKS_TOTAL,
      SUM(s.BOOKS_AUTO_POST)                        AS BOOKS_AUTO_POST,
      SUM(s.BOOKS_OPEN)                             AS BOOKS_OPEN,
      SUM(s.BOOKS_ANALYSED)                         AS BOOKS_ANALYSED,
      SUM(s.CASES_READY)                            AS CASES_READY,
      SUM(s.CASES_READY - s.CASES_ACCEPTED - s.CASES_REJECTED) AS CASES_PENDING_REVIEW,
      SUM(s.CASES_ACCEPTED)                         AS CASES_ACCEPTED,
      SUM(s.CASES_REJECTED)                         AS CASES_REJECTED,
      SUM(s.CASES_CARRIED_FORWARD)                  AS CASES_CARRIED_FORWARD
    FROM RECON_SESSION s
    WHERE s.REGION_DAY_ID = p_region_day_id
    GROUP BY s.REGION_DAY_ID
  ) src
  ON (t.REGION_DAY_ID = src.REGION_DAY_ID)
  WHEN MATCHED THEN UPDATE SET
    t.RECONS_IN_SCOPE       = src.RECONS_IN_SCOPE,
    t.RECONS_READY          = src.RECONS_READY,
    t.RECONS_SIGNED_OFF     = src.RECONS_SIGNED_OFF,
    t.BOOKS_TOTAL           = src.BOOKS_TOTAL,
    t.BOOKS_AUTO_POST       = src.BOOKS_AUTO_POST,
    t.BOOKS_OPEN            = src.BOOKS_OPEN,
    t.BOOKS_ANALYSED        = src.BOOKS_ANALYSED,
    t.CASES_READY           = src.CASES_READY,
    t.CASES_PENDING_REVIEW  = src.CASES_PENDING_REVIEW,
    t.CASES_ACCEPTED        = src.CASES_ACCEPTED,
    t.CASES_REJECTED        = src.CASES_REJECTED,
    t.CASES_CARRIED_FORWARD = src.CASES_CARRIED_FORWARD,
    t.DAY_STATUS = CASE
      WHEN src.RECONS_SIGNED_OFF = src.RECONS_IN_SCOPE THEN 'SIGNED_OFF'
      WHEN src.RECONS_READY      = src.RECONS_IN_SCOPE THEN 'READY'
      WHEN src.RECONS_READY > 0                        THEN 'PARTIAL'
      ELSE t.DAY_STATUS END,
    t.READY_BEFORE_SHIFT = CASE
      WHEN t.READY_BEFORE_SHIFT IS NOT NULL THEN t.READY_BEFORE_SHIFT
      WHEN src.RECONS_READY = src.RECONS_IN_SCOPE
       AND SYSTIMESTAMP <= t.SHIFT_START_UTC THEN 'Y'
      WHEN src.RECONS_READY = src.RECONS_IN_SCOPE THEN 'N'
      ELSE NULL END,
    t.COUNTERS_REFRESHED_TS = SYSTIMESTAMP;
END REFRESH_REGION_DAY_COUNTERS;
