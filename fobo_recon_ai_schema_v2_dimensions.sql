-- Business date is a dimension, not a DATE column. Holidays differ by region, so
-- 08 Sep can be a business day in EMEA and a holiday in APAC. PRIOR_BUSINESS_DATE
-- is what makes carry-forward of unresolved breaks resolvable in one join.
CREATE TABLE BUSINESS_CALENDAR (
  CALENDAR_ID           NUMBER(19)      GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  REGION_CODE           VARCHAR2(10)    NOT NULL,
  BUSINESS_DATE         DATE            NOT NULL,
  IS_BUSINESS_DAY       CHAR(1)         DEFAULT 'Y' NOT NULL,
  PRIOR_BUSINESS_DATE   DATE,
  NEXT_BUSINESS_DATE    DATE,
  DAY_OF_WEEK           NUMBER(1)       NOT NULL,
  IS_MONTH_END          CHAR(1)         DEFAULT 'N' NOT NULL,
  IS_QUARTER_END        CHAR(1)         DEFAULT 'N' NOT NULL,
  IS_YEAR_END           CHAR(1)         DEFAULT 'N' NOT NULL,
  IS_FREEZE_PERIOD      CHAR(1)         DEFAULT 'N' NOT NULL,
  HOLIDAY_NAME          VARCHAR2(80),
  CONSTRAINT FK_CALENDAR_REGION FOREIGN KEY (REGION_CODE) REFERENCES REGION (REGION_CODE),
  CONSTRAINT UK_BUSINESS_CALENDAR UNIQUE (REGION_CODE, BUSINESS_DATE),
  CONSTRAINT CK_CALENDAR_BUSDAY CHECK (IS_BUSINESS_DAY IN ('Y','N'))
);

CREATE INDEX IX_CALENDAR_LOOKUP ON BUSINESS_CALENDAR (BUSINESS_DATE, IS_BUSINESS_DAY);

-- Which regions a recon actually runs in. A recon may be single-region.
CREATE TABLE RECON_REGION_SCOPE (
  SCOPE_ID              NUMBER(19)      GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  RECON_ID              NUMBER(19)      NOT NULL,
  REGION_CODE           VARCHAR2(10)    NOT NULL,
  REQUIRES_GLOBAL_SIGNOFF CHAR(1)       DEFAULT 'Y' NOT NULL,
  IS_ACTIVE             CHAR(1)         DEFAULT 'Y' NOT NULL,
  CONSTRAINT FK_SCOPE_RECON  FOREIGN KEY (RECON_ID)    REFERENCES RECON_DEFINITION (RECON_ID),
  CONSTRAINT FK_SCOPE_REGION FOREIGN KEY (REGION_CODE) REFERENCES REGION (REGION_CODE),
  CONSTRAINT UK_RECON_REGION_SCOPE UNIQUE (RECON_ID, REGION_CODE)
);


