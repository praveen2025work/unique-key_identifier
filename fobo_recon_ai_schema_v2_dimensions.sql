-- Carry unresolved breaks into the next business date. Run at session open.
CREATE OR REPLACE PROCEDURE CARRY_FORWARD_BREAKS (
  p_session_id IN NUMBER
) AS
  v_region   VARCHAR2(10);
  v_bus_date DATE;
  v_prior    DATE;
BEGIN
  SELECT REGION_CODE, BUSINESS_DATE INTO v_region, v_bus_date
  FROM RECON_SESSION WHERE SESSION_ID = p_session_id;

  SELECT PRIOR_BUSINESS_DATE INTO v_prior
  FROM BUSINESS_CALENDAR
  WHERE REGION_CODE = v_region AND BUSINESS_DATE = v_bus_date;

  UPDATE RECON_EXCEPTION e
     SET (e.FIRST_SEEN_BUS_DATE, e.AGE_BUSINESS_DAYS,
          e.CARRIED_FROM_EXC_ID, e.PRIOR_DAY_DELTA) = (
       SELECT p.FIRST_SEEN_BUS_DATE, p.AGE_BUSINESS_DAYS + 1,
              p.EXCEPTION_ID, p.DELTA_AMOUNT
       FROM RECON_EXCEPTION p
       WHERE p.PERSISTENT_BREAK_KEY = e.PERSISTENT_BREAK_KEY
         AND p.BUSINESS_DATE = v_prior
         AND p.REGION_CODE = v_region
         AND ROWNUM = 1)
   WHERE e.SESSION_ID = p_session_id
     AND EXISTS (
       SELECT 1 FROM RECON_EXCEPTION p
       WHERE p.PERSISTENT_BREAK_KEY = e.PERSISTENT_BREAK_KEY
         AND p.BUSINESS_DATE = v_prior
         AND p.REGION_CODE = v_region);

  UPDATE RECON_SESSION
     SET CASES_CARRIED_FORWARD = (
       SELECT COUNT(*) FROM RECON_EXCEPTION
       WHERE SESSION_ID = p_session_id AND AGE_BUSINESS_DAYS > 0)
   WHERE SESSION_ID = p_session_id;
END CARRY_FORWARD_BREAKS;
